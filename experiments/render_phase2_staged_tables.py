"""Render the staged-audit CSV outputs as plain Markdown tables.

Run phase2_staged_audit.py first, then this script. No models are fitted here.
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent
DATA = ROOT / "phase2_staged_audit"


def read(name):
    return pd.read_csv(DATA / name)


def fmt(value):
    if pd.isna(value):
        return "—"
    if isinstance(value, (float, np.floating)):
        if abs(value) >= 1 and float(value).is_integer():
            return str(int(value))
        return f"{value:.3f}"
    return str(value).replace("|", r"\|")


def table(frame):
    headers = list(frame.columns)
    rows = ["| " + " | ".join(headers) + " |",
            "| " + " | ".join("---" for _ in headers) + " |"]
    rows += ["| " + " | ".join(fmt(value) for value in row) + " |"
             for row in frame.itertuples(index=False, name=None)]
    return "\n".join(rows)


def interval_index(frame, method="order"):
    rows = frame.loc[frame.method.eq(method)]
    return {(r.stage, r.metric): f"{r.low:.3f}–{r.high:.3f}" for r in rows.itertuples()}


def main():
    parts = ["# Staged late-delivery audit: tables and caveats",
             "All values below are generated by `experiments/phase2_staged_audit.py` with seed 42. "
             "New test comparisons are post hoc diagnostics. `AP/rate` is average precision divided by "
             "the late rate of that same cohort. `P/R/L@k` means precision, recall, and lift among the "
             "highest-scored k% of orders. Intervals are 95% percentile intervals from 1,000 resamples.",
             "## 1. Information ladder"]
    ladder = read("information_ladder.csv")
    mean = ladder.loc[ladder.period.ne("test")].groupby("stage", sort=False).mean(numeric_only=True).reset_index()
    mean["period"] = "validation mean"
    mean["orders"] = np.nan
    main = pd.concat([ladder, mean], ignore_index=True)
    main["period"] = pd.Categorical(main.period,
        ["validation_1", "validation_2", "validation_3", "validation_4", "validation_5",
         "validation mean", "test"], ordered=True)
    main["stage"] = pd.Categorical(main.stage, ["checkout", "approval", "handover"], ordered=True)
    main = main.sort_values(["stage", "period"])
    parts.append(table(main[["stage", "period", "orders", "late_rate", "pr_auc", "ap_over_rate", "roc_auc",
                             "precision_at_5", "recall_at_5", "lift_at_5", "precision_at_10",
                             "recall_at_10", "lift_at_10"]]))
    ci = read("test_intervals.csv")
    order = ci.loc[ci.method.eq("order")]
    parts.append("### Test 95% order-bootstrap intervals for every ranking and top-k measure")
    parts.append(table(order[["stage", "metric", "low", "high"]]))
    parts.append("Stage 0b was not fitted: `shipping_limit_date` has no creation/revision timestamp, "
                 "so checkout availability cannot be asserted. The Stage 0 model and 26 May 2018 boundary "
                 "were not changed. Stage 1 uses approval time; Stage 2 uses carrier handover time. "
                 "Invalid or absent event timestamps make a stage unavailable; at handover, approval "
                 "fields recorded later are missing and receive training-fold median imputation.")
    parts.append(table(read("coverage.csv")))
    parts.append("Caveat: the ordinary stage rows cover slightly different orders. The following "
                 "sensitivity refits all three stages on the same sequential-event training orders and "
                 "scores the same sequential-event test orders.")
    seq = read("sequential_same_train_and_test.csv")
    parts.append(table(seq.loc[seq.period.eq("test"), ["stage", "fit_orders", "orders", "late", "pr_auc",
                                                       "ap_over_rate", "roc_auc", "lift_at_10"]]))

    parts.append("## 2. Within-month ranking")
    months = read("within_month.csv")
    parts.append(table(months[["stage", "month", "orders", "late", "roc_auc", "roc_auc_low",
                               "roc_auc_high", "ap_over_rate", "ap_over_rate_low", "ap_over_rate_high",
                               "lift_at_10", "lift_at_10_low", "lift_at_10_high"]]))
    parts.append(table(read("within_month_pair_weighted_auc.csv")))
    parts.append("Caveat: June–August are post-hoc slices of the opened test. The pair-weighted AUC "
                 "compares late and on-time orders only within the same purchase month; May is a partial month and is excluded.")

    parts.append("## 3. Rolling monthly refit")
    rolling = read("rolling_refit.csv")
    frozen = months[["stage", "month", "roc_auc", "ap_over_rate", "lift_at_10"]]
    comparison = rolling.merge(frozen, on=["stage", "month"], suffixes=("_rolling", "_frozen"))
    parts.append(table(comparison[["stage", "month", "fit_orders", "roc_auc_frozen", "roc_auc_rolling",
                                   "ap_over_rate_frozen", "ap_over_rate_rolling", "lift_at_10_frozen",
                                   "lift_at_10_rolling"]]))
    parts.append("Caveat: the monthly refit uses only outcomes known at that month's start, but "
                 "these adaptations were devised after the original test was opened. A Stage 2 score "
                 "is made when handover occurs, possibly after the purchase month ends.")

    parts.append("## 4. Simple univariate and fixed-rule baselines")
    base = read("simple_baselines.csv")
    v = base.loc[base.period.ne("test")].groupby(["stage", "feature"], as_index=False)[
        ["roc_auc", "ap_over_rate"]].mean()
    t = base.loc[base.period.eq("test")]
    joined = v.merge(t, on=["stage", "feature"], suffixes=("_val_mean", "_test"))
    parts.append(table(joined[["stage", "feature", "roc_auc_val_mean", "ap_over_rate_val_mean",
                               "roc_auc_test", "ap_over_rate_test"]]))
    parts.append("Univariate directions were fixed from the feature meanings: shorter promise and "
                 "fewer days left, and longer distance, route time, seller handover time or current "
                 "handover delay indicate higher risk; same-state is treated as lower risk. "
                 "No direction was reversed after seeing the test.")
    parts.append("The fixed rule, chosen without fitting weights, is: route typical days + seller past "
                 "handover days + distance/500 − promised days − same-state indicator; at Stage 2 it "
                 "also adds handover-after-approval days and subtracts days left at handover. Positive "
                 "scores mean higher risk. Compare its rows with the full logistic rows in Section 1.")
    parts.append("Caveat: these directions and coefficients are exploratory; the test has already "
                 "been opened. A stronger test result cannot be used to replace the frozen model.")

    parts.append("## 5. Severity targets")
    severity = read("severity.csv")
    val = severity.loc[severity.period.ne("test")].groupby(["stage", "target"], as_index=False)[
        ["late_rate", "roc_auc", "ap_over_rate", "lift_at_10"]].mean()
    val["period"] = "validation mean"
    sev = pd.concat([val, severity.loc[severity.period.eq("test")]], ignore_index=True)
    parts.append(table(sev[["stage", "target", "period", "late_rate", "roc_auc",
                            "ap_over_rate", "lift_at_10"]]))
    parts.append("Caveat: >3 and >7 refer to calendar days past the promise. These are newly fitted "
                 "targets, evaluated post hoc on the same test period; Stage 2 may observe handover after the promise.")

    parts.append("## 6. Intercept check")
    parts.append(table(read("intercept_check.csv")[["stage", "fit", "fit_orders", "train_late_rate",
                                                     "eval_orders", "eval_late_rate", "mean_predicted"]]))
    parts.append("Caveat: validation fits differ by window, whereas each final fit is one model. "
                 "Mean predicted risk is a calibration check, not a ranking score.")

    parts.append("## 7. Order versus purchase-week bootstrap")
    intervals = read("test_intervals.csv")
    intervals = intervals.loc[intervals.stage.isin(["checkout", "handover"])
                              & intervals.metric.isin(["pr_auc", "roc_auc", "precision_at_10"])]
    parts.append(table(intervals[["stage", "method", "metric", "low", "high"]]))
    parts.append("Caveat: only 15 purchase weeks occur in the test. The week bootstrap captures "
                 "some time clustering, but neither interval method captures model-selection uncertainty.")

    parts.append("## 8. Input availability and removal")
    availability = read("feature_availability.csv").drop_duplicates("input")
    parts.append(table(availability[["input", "source_column", "depends_on_timestamp",
                                     "availability_uncertain"]]))
    parts.append("The source data lack recording/revision timestamps for many checkout fields. "
                 "The script asserts ordering for timestamped stage events and the existing point-in-time "
                 "history helper; it cannot prove that an undated promise, payment, catalog or profile field "
                 "was already recorded at purchase.")
    parts.append(table(read("availability_removals.csv")[["stage", "removed", "columns",
                                                          "test_roc_auc", "test_ap_over_rate",
                                                          "test_top10_lift", "delta_roc_vs_full",
                                                          "delta_ap_ratio_vs_full"]]))
    parts.append("Caveat: each removal refits the same logistic setting on eligible primary training rows; "
                 "the test comparisons are post hoc. One-at-a-time removals leave correlated derived "
                 "inputs in place. `promise_bundle` therefore removes every promise-dependent input "
                 "together; `payment_bundle` removes both payment inputs.")

    parts.append("## 9. Leakage-oriented sanity checks")
    parts.append(table(read("stage2_grouped_permutation.csv")))
    parts.append(table(read("stage2_handover_shuffle.csv")))
    counts = json.loads((DATA / "stage2_sanity_counts.json").read_text())
    parts.append(table(pd.DataFrame([{"Stage 2 test orders": counts["test_stage2_orders"],
                                     "handover after promise": counts["handover_after_promised_date"],
                                     "all late in that group": counts["all_late_after_promise"]}])))
    parts.append(table(pd.DataFrame([counts["before_or_on_promise_metrics"]])[
        ["orders", "late", "late_rate", "pr_auc", "ap_over_rate", "roc_auc", "lift_at_10"]]))
    parts.append("Caveat: permutation is on the already-open test and measures score dependence, "
                 "not causal feature value. A negative `mean_ap_decrease` means the shuffle increased AP. "
                 "Handover-after-promise rows have an almost disclosed outcome; the pre-promise subset "
                 "is shown separately.")

    parts.append("## Anything that surprised me")
    checkout_test = ladder.loc[ladder.stage.eq("checkout") & ladder.period.eq("test")].iloc[0]
    handover_test = ladder.loc[ladder.stage.eq("handover") & ladder.period.eq("test")].iloc[0]
    weighted = read("within_month_pair_weighted_auc.csv")
    checkout_weighted = weighted.loc[weighted.stage.eq("checkout"), "pair_weighted_roc_auc"].iloc[0]
    august = months.loc[months.stage.eq("checkout") & months.month.eq("2018-08"), "roc_auc"].iloc[0]
    rule_test = base.loc[base.stage.eq("checkout") & base.feature.eq("fixed_rule")
                         & base.period.eq("test"), "roc_auc"].iloc[0]
    rule_val = v.loc[v.stage.eq("checkout") & v.feature.eq("fixed_rule"), "roc_auc"].iloc[0]
    checkout_val = ladder.loc[ladder.stage.eq("checkout") & ladder.period.ne("test"), "roc_auc"].mean()
    ablations = read("availability_removals.csv")
    checkout_no_promise = ablations.loc[ablations.stage.eq("checkout")
                                        & ablations.removed.eq("promise_bundle"), "test_roc_auc"].iloc[0]
    handover_no_promise = ablations.loc[ablations.stage.eq("handover")
                                        & ablations.removed.eq("promise_bundle"), "test_roc_auc"].iloc[0]
    before_promise = counts["before_or_on_promise_metrics"]
    parts.append(f"- Checkout pooled test ROC-AUC is {checkout_test.roc_auc:.3f}, but within-month "
                 f"pair-weighted ROC-AUC for June–August is {checkout_weighted:.3f}; August alone is "
                 f"{august:.3f}.")
    parts.append(f"- A fixed, hand-written checkout score gets test ROC-AUC {rule_test:.3f} versus "
                 f"{checkout_test.roc_auc:.3f} for the frozen logistic model, although its validation "
                 f"mean ROC-AUC is {rule_val:.3f} versus {checkout_val:.3f}. This is a post-hoc "
                 "comparison, not a new selection.")
    parts.append(f"- Removing the full promise bundle changes checkout test ROC-AUC from "
                 f"{checkout_test.roc_auc:.3f} to {checkout_no_promise:.3f} and Stage 2 from "
                 f"{handover_test.roc_auc:.3f} to {handover_no_promise:.3f}. Removing only "
                 "`promised_days` barely changes either score because promise-derived inputs remain.")
    parts.append(f"- Stage 2 test PR-AUC is {handover_test.pr_auc:.3f}; after excluding "
                 f"{counts['handover_after_promised_date']} handovers after the promised date it is "
                 f"{before_promise['pr_auc']:.3f} on {before_promise['orders']:,} orders. Those "
                 f"{counts['handover_after_promised_date']} were all late.")
    parts.append("- The previous staged validation experiment used purchase-to-handover delay and "
                 "excluded post-promise handovers. This audit uses the requested approval-to-handover "
                 "delay and reports the full eligible handover cohort, so those older results are not "
                 "directly comparable.")
    (DATA / "TABLES.md").write_text("\n\n".join(parts) + "\n")
    print(DATA / "TABLES.md")


if __name__ == "__main__":
    main()
